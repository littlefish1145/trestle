// Package cmake reverse-exports a trestle.toml project into a CMakeLists.txt.
//
// The export is experimental and best-effort: targets, sources, scopes and
// tests map cleanly onto CMake, while Trestle-only concepts (rules, tasks,
// compiler presets, conditional readiness, vcpkg usage resolved at build
// time) are preserved as comments so nothing is silently lost.
package cmake

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	"trestle/internal/config"
	"trestle/internal/fsx"
)

// Options configures a CMake export. Root is the project directory that source
// globs resolve against.
type Options struct {
	// Root is the project directory that source globs resolve against.
	// It defaults to the directory of the loaded configuration.
	Root string
}

// Result is the generated CMakeLists.txt content plus the number of exported
// targets and any warnings about content that could only be preserved as
// comments.
type Result struct {
	Content  string
	Targets  int
	Warnings []string
}

// Generate renders cfg as CMakeLists.txt content.
func Generate(cfg config.Config, opts Options) (Result, error) {
	root := opts.Root
	if root == "" {
		root = cfg.Root()
	}
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return Result{}, err
	}
	g := &generator{root: absRoot, cfg: cfg, languages: map[string]bool{}}
	if err := g.run(); err != nil {
		return Result{}, err
	}
	return Result{Content: strings.Join(g.lines, "\n") + "\n", Targets: g.targets, Warnings: g.warnings}, nil
}

type generator struct {
	root      string
	cfg       config.Config
	lines     []string
	warnings  []string
	languages map[string]bool
	targets   int
	tests     bool
}

func (g *generator) run() error {
	names := make([]string, 0, len(g.cfg.Targets))
	for name := range g.cfg.Targets {
		names = append(names, name)
	}
	sort.Strings(names)
	sources := make(map[string][]string, len(names))
	for _, name := range names {
		target := g.cfg.Targets[name]
		patterns := make([]string, len(target.Sources))
		for i, pattern := range target.Sources {
			patterns[i] = pattern
			if !filepath.IsAbs(pattern) {
				patterns[i] = filepath.Join(g.root, pattern)
			}
		}
		files, err := fsx.ResolveSources(patterns)
		if err != nil {
			return fmt.Errorf("target %q source glob: %w", name, err)
		}
		if len(files) == 0 {
			return fmt.Errorf("E_CONFIG_MISSING_REQUIRED: target %q source pattern matched no files", name)
		}
		sources[name] = files
		if target.Type != "shader" {
			g.detectLanguages(files)
		}
		if target.Type == "test" {
			g.tests = true
		}
	}

	g.line("# Generated by trestle export-cmake from trestle.toml (schema %d).", g.cfg.SchemaVersion)
	g.line("# trestle.toml remains the source of truth; regenerate with `trestle export-cmake -force`.")
	g.line("")
	g.line("cmake_minimum_required(VERSION 3.20)")
	g.line("")
	g.line("project(%s LANGUAGES %s)", quote(g.cfg.Project.Name), strings.Join(g.orderedLanguages(), " "))
	g.line("")
	g.emitStandards()
	g.emitProjectFlags()
	if g.tests {
		g.line("enable_testing()")
		g.line("")
	}
	for _, name := range names {
		target := g.cfg.Targets[name]
		if target.Type == "shader" {
			g.warnings = append(g.warnings, fmt.Sprintf("shader target %q (stage %s) is not exported; trestle compiles Vulkan shaders outside CMake", name, target.ShaderStage))
			g.line("# shader target %q (stage %s) is not exported; trestle compiles Vulkan shaders outside CMake.", name, target.ShaderStage)
			g.line("")
			continue
		}
		if err := g.emitTarget(name, target, sources[name]); err != nil {
			return err
		}
		g.targets++
	}
	g.emitDefaults()
	g.emitUnexportedSections()
	return nil
}

func (g *generator) detectLanguages(files []string) {
	for _, file := range files {
		switch strings.ToLower(filepath.Ext(file)) {
		case ".c":
			g.languages["C"] = true
		case ".cpp", ".cc", ".cxx", ".c++":
			g.languages["CXX"] = true
		case ".cu":
			g.languages["CUDA"] = true
		}
	}
}

func (g *generator) orderedLanguages() []string {
	order := []string{"C", "CXX", "CUDA"}
	languages := make([]string, 0, len(order))
	for _, language := range order {
		if g.languages[language] {
			languages = append(languages, language)
		}
	}
	if len(languages) == 0 {
		return []string{"CXX"}
	}
	return languages
}

func (g *generator) emitStandards() {
	if standard := cStandard(g.cfg.Build.CStandard); standard != "" {
		g.line("set(CMAKE_C_STANDARD %s)", standard)
		g.line("set(CMAKE_C_STANDARD_REQUIRED ON)")
		g.line("set(CMAKE_C_EXTENSIONS OFF)")
	} else if g.cfg.Build.CStandard != "" {
		g.warnings = append(g.warnings, fmt.Sprintf("build.c_standard %q is not a recognizable C standard; not exported", g.cfg.Build.CStandard))
	}
	if standard := cxxStandard(g.cfg.Build.CXXStandard); standard != "" {
		g.line("set(CMAKE_CXX_STANDARD %s)", standard)
		g.line("set(CMAKE_CXX_STANDARD_REQUIRED ON)")
		g.line("set(CMAKE_CXX_EXTENSIONS OFF)")
	} else if g.cfg.Build.CXXStandard != "" {
		g.warnings = append(g.warnings, fmt.Sprintf("build.cxx_standard %q is not a recognizable C++ standard; not exported", g.cfg.Build.CXXStandard))
	}
	if g.cfg.Build.CompileCommands != "" {
		g.line("set(CMAKE_EXPORT_COMPILE_COMMANDS ON)")
	}
	if g.cfg.Build.CStandard != "" || g.cfg.Build.CXXStandard != "" || g.cfg.Build.CompileCommands != "" {
		g.line("")
	}
}

func (g *generator) emitProjectFlags() {
	if len(g.cfg.Build.CompileFlags) > 0 {
		g.line("add_compile_options(%s)", strings.Join(mapStrings(g.cfg.Build.CompileFlags, quote), " "))
	}
	if len(g.cfg.Build.CFlags) > 0 {
		g.line("add_compile_options(%s)", strings.Join(languageFlags("C", g.cfg.Build.CFlags), " "))
	}
	if len(g.cfg.Build.CXXFlags) > 0 {
		g.line("add_compile_options(%s)", strings.Join(languageFlags("CXX", g.cfg.Build.CXXFlags), " "))
	}
	if len(g.cfg.Build.LinkFlags) > 0 {
		g.line("add_link_options(%s)", strings.Join(mapStrings(g.cfg.Build.LinkFlags, quote), " "))
	}
	if len(g.cfg.Build.CompileFlags) > 0 || len(g.cfg.Build.CFlags) > 0 || len(g.cfg.Build.CXXFlags) > 0 || len(g.cfg.Build.LinkFlags) > 0 {
		g.line("")
	}
}

func (g *generator) emitTarget(name string, target config.Target, files []string) error {
	switch target.Type {
	case "executable", "test":
		g.line("add_executable(%s", quote(name))
	case "static":
		g.line("add_library(%s STATIC", quote(name))
	case "shared":
		g.line("add_library(%s SHARED", quote(name))
	default:
		return fmt.Errorf("target %q has unsupported type %q", name, target.Type)
	}
	for _, file := range files {
		g.line("  %s", quote(g.relative(file)))
	}
	g.line(")")
	if target.OutputName != "" && target.OutputName != name {
		g.line("set_target_properties(%s PROPERTIES OUTPUT_NAME %s)", quote(name), quote(target.OutputName))
	}
	if target.ExportAllSymbols {
		g.line("set_target_properties(%s PROPERTIES WINDOWS_EXPORT_ALL_SYMBOLS ON)", quote(name))
	}
	if len(target.IncludeDirs) > 0 {
		g.line("target_include_directories(%s PUBLIC %s)", quote(name), strings.Join(mapStrings(target.IncludeDirs, quote), " "))
	}
	if len(target.PrivateIncludeDirs) > 0 {
		g.line("target_include_directories(%s PRIVATE %s)", quote(name), strings.Join(mapStrings(target.PrivateIncludeDirs, quote), " "))
	}
	if len(target.Defines) > 0 {
		g.line("target_compile_definitions(%s PUBLIC %s)", quote(name), strings.Join(mapStrings(target.Defines, quote), " "))
	}
	if len(target.PrivateDefines) > 0 {
		g.line("target_compile_definitions(%s PRIVATE %s)", quote(name), strings.Join(mapStrings(target.PrivateDefines, quote), " "))
	}
	if len(target.CompileOptions) > 0 {
		g.line("target_compile_options(%s PRIVATE %s)", quote(name), strings.Join(mapStrings(target.CompileOptions, quote), " "))
	}
	if len(target.CFlags) > 0 {
		g.line("target_compile_options(%s PRIVATE %s)", quote(name), strings.Join(languageFlags("C", target.CFlags), " "))
	}
	if len(target.CXXFlags) > 0 {
		g.line("target_compile_options(%s PRIVATE %s)", quote(name), strings.Join(languageFlags("CXX", target.CXXFlags), " "))
	}
	if len(target.InterfaceCompile) > 0 {
		g.line("target_compile_options(%s INTERFACE %s)", quote(name), strings.Join(mapStrings(target.InterfaceCompile, quote), " "))
	}
	if len(target.LibraryDirs) > 0 {
		g.line("target_link_directories(%s PRIVATE %s)", quote(name), strings.Join(mapStrings(target.LibraryDirs, quote), " "))
	}
	if len(target.Libraries) > 0 {
		g.line("target_link_libraries(%s PRIVATE %s)", quote(name), strings.Join(mapStrings(target.Libraries, quote), " "))
	}
	if len(target.LinkOptions) > 0 {
		g.line("target_link_options(%s PRIVATE %s)", quote(name), strings.Join(mapStrings(target.LinkOptions, quote), " "))
	}
	if len(target.InterfaceLink) > 0 {
		g.line("target_link_options(%s INTERFACE %s)", quote(name), strings.Join(mapStrings(target.InterfaceLink, quote), " "))
	}
	for _, dep := range target.Dependencies {
		g.emitDependency(name, dep)
	}
	if target.Type == "test" {
		g.emitTest(name, target)
	}
	if target.When != "" {
		g.line("# trestle condition: when = %s", target.When)
	}
	if len(target.RequiresTools) > 0 || target.RequiresWSL != "" {
		g.line("# trestle readiness: requires_tools = [%s], requires_wsl = %s", strings.Join(target.RequiresTools, ", "), target.RequiresWSL)
	}
	g.line("")
	return nil
}

func (g *generator) emitDependency(name string, dep config.Dependency) {
	scope := cmakeScope(dep.Scope)
	if dep.Target != "" {
		g.line("target_link_libraries(%s %s %s)", quote(name), scope, quote(dep.Target))
		return
	}
	pkg := g.cfg.Packages[dep.Package]
	g.line("# trestle package %q (port %q) usage", dep.Package, pkg.Port)
	if len(pkg.IncludeDirs) > 0 {
		g.line("target_include_directories(%s %s %s)", quote(name), scope, strings.Join(mapStrings(pkg.IncludeDirs, quote), " "))
	}
	if len(pkg.Defines) > 0 {
		g.line("target_compile_definitions(%s %s %s)", quote(name), scope, strings.Join(mapStrings(pkg.Defines, quote), " "))
	}
	if len(pkg.LibraryDirs) > 0 {
		g.line("target_link_directories(%s %s %s)", quote(name), scope, strings.Join(mapStrings(pkg.LibraryDirs, quote), " "))
	}
	if len(pkg.Libraries) > 0 {
		g.line("target_link_libraries(%s %s %s)", quote(name), scope, strings.Join(mapStrings(pkg.Libraries, quote), " "))
	}
	if len(pkg.IncludeDirs) == 0 && len(pkg.Defines) == 0 && len(pkg.LibraryDirs) == 0 && len(pkg.Libraries) == 0 {
		provider := pkg.Provider
		if provider == "" {
			provider = "vcpkg"
		}
		g.warnings = append(g.warnings, fmt.Sprintf("package %q resolves its usage through %s at build time; only a comment was exported", dep.Package, provider))
		g.line("%s", "# usage is resolved by trestle's "+provider+" integration at build time")
	}
}

func (g *generator) emitTest(name string, target config.Target) {
	command := quote(name)
	for _, arg := range target.TestArgs {
		command += " " + quote(arg)
	}
	g.line("add_test(NAME %s COMMAND %s)", quote(name), command)
	properties := make([]string, 0, 2)
	if target.TestGroup != "" {
		properties = append(properties, fmt.Sprintf("LABELS %s", quote(target.TestGroup)))
	}
	if target.TestWorkingDir != "" {
		properties = append(properties, fmt.Sprintf("WORKING_DIRECTORY %s", quote(target.TestWorkingDir)))
	}
	if len(properties) > 0 {
		g.line("set_tests_properties(%s PROPERTIES %s)", quote(name), strings.Join(properties, " "))
	}
}

func (g *generator) emitDefaults() {
	if len(g.cfg.Build.DefaultTargets) == 0 {
		return
	}
	g.line("# trestle default targets: %s", strings.Join(g.cfg.Build.DefaultTargets, ", "))
	g.line("")
}

func (g *generator) emitUnexportedSections() {
	unexported := make([]string, 0, 4)
	if len(g.cfg.CompilerPresets) > 0 {
		unexported = append(unexported, fmt.Sprintf("compiler_presets (%d)", len(g.cfg.CompilerPresets)))
	}
	if len(g.cfg.Rules) > 0 {
		unexported = append(unexported, fmt.Sprintf("rules (%d)", len(g.cfg.Rules)))
	}
	if len(g.cfg.Tasks) > 0 {
		unexported = append(unexported, fmt.Sprintf("tasks (%d)", len(g.cfg.Tasks)))
	}
	if g.cfg.Build.AutoCompileShaders {
		unexported = append(unexported, "auto_compile_shaders")
	}
	if len(unexported) == 0 {
		return
	}
	g.line("# trestle-only sections are not exported to CMake: %s.", strings.Join(unexported, ", "))
	g.line("# They continue to live in trestle.toml and apply to `trestle build`.")
}

func (g *generator) relative(path string) string {
	relative, err := filepath.Rel(g.root, path)
	if err == nil && relative != ".." && !strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
		return filepath.ToSlash(relative)
	}
	g.warnings = append(g.warnings, fmt.Sprintf("source %s lies outside the project; exporting its absolute path", path))
	return filepath.ToSlash(path)
}

func (g *generator) line(format string, args ...any) {
	g.lines = append(g.lines, fmt.Sprintf(format, args...))
}

func cmakeScope(scope string) string {
	switch strings.ToLower(scope) {
	case "public":
		return "PUBLIC"
	case "interface":
		return "INTERFACE"
	default:
		return "PRIVATE"
	}
}

func cStandard(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	if !strings.HasPrefix(value, "c") || strings.HasPrefix(value, "c++") {
		return ""
	}
	digits := value[1:]
	if digits == "" {
		return ""
	}
	for _, char := range digits {
		if char < '0' || char > '9' {
			return ""
		}
	}
	return digits
}

func cxxStandard(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	if strings.HasPrefix(value, "c++") {
		value = value[3:]
	} else if strings.HasPrefix(value, "cxx") {
		value = value[3:]
	} else {
		return ""
	}
	if value == "" {
		return ""
	}
	for _, char := range value {
		if char < '0' || char > '9' {
			return ""
		}
	}
	return value
}

// languageFlags wraps each flag in a compile-language generator expression so
// C-only and C++-only flags keep their trestle.toml meaning in CMake.
func languageFlags(language string, flags []string) []string {
	wrapped := make([]string, 0, len(flags))
	for _, flag := range flags {
		escaped := strings.ReplaceAll(flag, `"`, `\"`)
		wrapped = append(wrapped, fmt.Sprintf(`"$<$<COMPILE_LANGUAGE:%s>:%s>"`, language, escaped))
	}
	return wrapped
}

func mapStrings(values []string, transform func(string) string) []string {
	result := make([]string, 0, len(values))
	for _, value := range values {
		result = append(result, transform(value))
	}
	return result
}

// quote escapes one CMake argument. Windows backslashes become forward
// slashes, which CMake accepts on every platform.
func quote(value string) string {
	if value == "" {
		return `""`
	}
	if !strings.ContainsAny(value, " \t\r\n;#\"$(){}") {
		return value
	}
	escaped := strings.ReplaceAll(value, `\`, `/`)
	escaped = strings.ReplaceAll(escaped, `"`, `\"`)
	return `"` + escaped + `"`
}
